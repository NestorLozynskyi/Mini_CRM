export const POPULAR = ['USD', 'EUR', 'GBP', 'UAH', 'PLN', 'CAD', 'AUD', 'CHF']

const NAMES = new Map(CURRENCIES)

export function currencyName(code: string): string {
  return NAMES.get(code) ?? code
}

export type CurrencyGroup = { label: 'Popular' | 'All currencies' | 'Results'; codes: string[] }

/** Групи списку: без пошуку — Popular і All currencies; з пошуком — збіги за кодом або назвою, точний код першим. */
export function currencyGroups(query: string): CurrencyGroup[] {
  const q = query.trim().toLowerCase()
  if (!q) {
    return [
      { label: 'Popular', codes: POPULAR },
      { label: 'All currencies', codes: CURRENCIES.map(([c]) => c).filter((c) => !POPULAR.includes(c)) },
    ]
  }
  const hits = CURRENCIES.filter(([c, n]) => c.toLowerCase().includes(q) || n.toLowerCase().includes(q)).map(([c]) => c)
  hits.sort((a, b) => (a.toLowerCase() === q ? -1 : 0) - (b.toLowerCase() === q ? -1 : 0))
  return hits.length ? [{ label: 'Results', codes: hits }] : []
}

/** Стан кнопок Save / Cancel: активні лише коли вибір відрізняється від збереженого і не йде збереження. */
export function currencyActions(selected: string, saved: string, saving = false): { dirty: boolean; canSave: boolean; canCancel: boolean } {
  const dirty = selected !== saved
  return { dirty, canSave: dirty && !saving, canCancel: dirty && !saving }
}
